-- 개발 초기에 화면을 채우려고 손으로 넣은 가짜 경기를 지운다.
--
-- 9600001~9600008 은 API-Football 이 준 id 가 아니라 그때 임의로 붙인 번호다
-- (실제 id 는 1550107 부터 시작한다). 킥오프 시각도 같은 순간에 90분 간격으로
-- 찍혀 있어 실제 일정이 아니다.
--
-- 이 대역을 통째로 비운다 — API-Football id 가 9,600,000 에 닿으려면 한참 남았고,
-- 그 사이에 같은 방식으로 또 시드가 들어가면 이 마이그레이션이 다시 걸러준다.
-- 예측·채팅·기준선은 fixtures 를 on delete cascade 로 참조하므로 같이 사라진다.
delete from fixtures where id >= 9600000;
