-- 경기별 기준 확률 갱신 (명세 2.2)
--
-- 기준선이 없으면 모든 경기가 같은 값(0.45/0.26/0.29)을 쓴다. 그러면 강팀의 홈 경기를
-- 맞혀도, 약체의 원정 승을 맞혀도 점수가 같아진다 — 로그 스코어가 실력을 재지 못한다.
--
-- 순위표 한 장(리그당 1회)으로 팀 전력을 재므로 주당 4회면 된다. 일정 수집 직후에
-- 돌려서 새로 들어온 경기도 같은 주기 안에 기준선을 갖게 한다.
select cron.schedule('sync-priors', '30 19 * * 0', $$ select invoke_sync('priors'); $$);
