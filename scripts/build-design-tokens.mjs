import { readFileSync, writeFileSync } from 'node:fs';
const t = JSON.parse(
  readFileSync(new URL('../design/system/tokens.json', import.meta.url), 'utf8')
);
const rows = Object.entries(t.colors).map(([k, v]) => `  --${k}: ${v};`);
for (const group of ['space', 'radius', 'type', 'motion'])
  for (const [k, v] of Object.entries(t[group]))
    rows.push(`  --${group}-${k}: ${v};`);
writeFileSync(
  new URL('../src/design/tokens.css', import.meta.url),
  `/* Generated by npm run design:tokens. Edit design/system/tokens.json. */\n:root {\n${rows.join('\n')}\n}\n`
);
const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
writeFileSync(
  new URL('../ios/Sources/DesignTokens.swift', import.meta.url),
  `// Generated by npm run design:tokens.\nimport SwiftUI\nenum DesignTokens {\n${Object.entries(
    t.colors
  )
    .map(([k, v]) => `    static let ${camel(k)} = Color(hex: 0x${v.slice(1)})`)
    .join('\n')}\n}\n`
);
